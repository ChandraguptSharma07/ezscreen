def test_write_md_report_emits_report_and_metrics(tmp_path):
    final_dir = tmp_path / "output"
    final_dir.mkdir()
    _write(final_dir / "state.csv", ["temperature", "potentialEnergy", "totalEnergy"], [
        {"temperature": "298.0", "potentialEnergy": "-120.0", "totalEnergy": "-100.0"},
        {"temperature": "301.5", "potentialEnergy": "-110.0", "totalEnergy": "-95.0"},
    ])
    summary = {
        "md_run_id": "ezs-x-md-lig-1",
        "run_id": "ezs-x",
        "ligand_id": "lig_1",
        "preset": "smoke",
        "pose_source": "unidock",
        "platform": "CUDA",
        "simulated_ps": 10.0,
        "potential_energy_kj_mol": -110.0,
        "kinetic_energy_kj_mol": 20.0,
    }

    md_runner._write_md_report(final_dir, summary)

    report = (final_dir / "md_report.html").read_text(encoding="utf-8")
    metrics = json.loads((final_dir / "md_metrics.json").read_text())
    assert "ezscreen MD report" in report
    assert "Temperature" in report
    assert metrics["frames"] == 2
    assert metrics["temperature"]["last"] == 301.5


