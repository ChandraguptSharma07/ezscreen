def test_run_md_simulation_waits_for_sync_probe_before_submit(tmp_path, monkeypatch):
    from pathlib import Path

    from ezscreen import checkpoint

    run = tmp_path / "ezs-md"
    (run / "receptor").mkdir(parents=True)
    (run / "output").mkdir(parents=True)
    (run / "receptor" / "receptor_prep.pdb").write_text("HEADER\nEND\n", encoding="utf-8")
    (run / "output" / "poses.sdf").write_text("pose\n", encoding="utf-8")
    _write(run / "output" / "scores.csv", ["ligand", "name"], [{"ligand": "lig_00000", "name": "A"}])

    steps: list[str] = []

    monkeypatch.setattr(md_runner, "_resolve_kaggle_credentials", lambda _path=None: ("alice", None))
    monkeypatch.setattr(md_runner, "_upload_md_dataset", lambda **_kwargs: "alice/ezscreen-md")
    monkeypatch.setattr(md_runner, "_wait_for_dataset", lambda _ref: steps.append("ready"))
    monkeypatch.setattr(md_runner, "_wait_for_dataset_sync", lambda _ref, **_kwargs: steps.append("sync"))
    monkeypatch.setattr(md_runner, "render_md_notebook", lambda **_kwargs: json.dumps({"cells": []}))
    monkeypatch.setattr(md_runner, "push_kernel", lambda **_kwargs: steps.append("push") or "alice/kernel")
    monkeypatch.setattr(md_runner, "poll_until_done", lambda **_kwargs: {"status": "complete", "error_type": None})

    def fake_download_md_output(_kernel_ref, work_dir):
        out_dir = Path(work_dir) / "kaggle_output" / "result"
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / "md_summary.json").write_text(json.dumps({"platform": "CUDA", "simulated_ps": 10.0}), encoding="utf-8")
        (out_dir / "state.csv").write_text("temperature,potentialEnergy,totalEnergy\n298,-100,-80\n", encoding="utf-8")
        return Path(work_dir) / "kaggle_output"

    monkeypatch.setattr(md_runner, "_download_md_output", fake_download_md_output)

    monkeypatch.setattr(checkpoint, "init_db", lambda: None)
    monkeypatch.setattr(checkpoint, "get_run", lambda _run_id: {"run_id": "ezs-md"})
    monkeypatch.setattr(checkpoint, "create_run", lambda *args, **kwargs: None)
    monkeypatch.setattr(checkpoint, "mark_run_complete", lambda *args, **kwargs: None)
    monkeypatch.setattr(checkpoint, "create_md_run", lambda *args, **kwargs: None)
    monkeypatch.setattr(checkpoint, "mark_md_run_failed", lambda *args, **kwargs: None)
    monkeypatch.setattr(checkpoint, "mark_md_run_complete", lambda *args, **kwargs: None)

    result = md_runner.run_md_simulation(
        run_id="ezs-md",
        ligand_id="lig_00000",
        preset="smoke",
        run_dir=run,
    )

    assert result["status"] == "complete"
    assert steps == ["ready", "sync", "push"]
