_STATE_HEADER_ALIASES: dict[str, tuple[str, ...]] = {
    "temperature": ("temperature", "Temperature (K)"),
    "potentialEnergy": ("potentialEnergy", "Potential Energy (kJ/mole)"),
    "kineticEnergy": ("kineticEnergy", "Kinetic Energy (kJ/mole)"),
    "totalEnergy": ("totalEnergy", "Total Energy (kJ/mole)"),
}


def _read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def _read_state_rows(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _series_values(rows: list[dict[str, str]], key: str) -> list[float]:
    values: list[float] = []
    aliases = _STATE_HEADER_ALIASES.get(key, (key,))
    for row in rows:
        raw = ""
        for alias in aliases:
            raw = str(row.get(alias, "")).strip()
            if raw:
                break
        if not raw:
            continue
        raw = raw.rstrip("%")
        try:
            values.append(float(raw))
        except ValueError:
            continue
    return values


def _line_points(values: list[float], width: int = 360, height: int = 120) -> str:
    if not values:
        return ""
    if len(values) == 1:
        return f"0,{height // 2} {width},{height // 2}"
    lo = min(values)
    hi = max(values)
    span = hi - lo or 1.0
    points: list[str] = []
    for idx, value in enumerate(values):
        x = idx * width / max(len(values) - 1, 1)
        y = height - ((value - lo) / span) * height
        points.append(f"{x:.1f},{y:.1f}")
    return " ".join(points)


def _chart_svg(values: list[float], *, unit: str, color: str, width: int = 420, height: int = 180) -> str:
    if not values:
        return ""
    left = 116
    right = 18
    top = 12
    bottom = 32
    plot_w = width - left - right
    plot_h = height - top - bottom
    lo = min(values)
    hi = max(values)
    span = hi - lo or 1.0

    def x_pos(idx: int) -> float:
        return left + (idx * plot_w / max(len(values) - 1, 1))

    def y_pos(value: float) -> float:
        return top + (plot_h - ((value - lo) / span) * plot_h)

    def fmt_tick(value: float) -> str:
        magnitude = max(abs(lo), abs(hi))
        if magnitude >= 10000:
            return f"{value:.0f}"
        if magnitude >= 1000:
            return f"{value:.1f}"
        return f"{value:.2f}"

    points = " ".join(f"{x_pos(i):.1f},{y_pos(v):.1f}" for i, v in enumerate(values))
    mid = (lo + hi) / 2.0
    y_ticks = [
        (top, hi),
        (top + plot_h / 2.0, mid),
        (top + plot_h, lo),
    ]
    x_ticks = [
        (left, 1),
        (left + plot_w / 2.0, max(1, len(values) // 2)),
        (left + plot_w, len(values)),
    ]

    y_tick_lines = "".join(
        f"<line x1='{left:.1f}' y1='{y:.1f}' x2='{left + plot_w:.1f}' y2='{y:.1f}' class='grid-line'></line>"
        for y, _ in y_ticks
    )
    y_tick_labels = "".join(
        f"<text x='{left - 14:.1f}' y='{y + 4:.1f}' text-anchor='end' class='axis-label'>{fmt_tick(value)}</text>"
        for y, value in y_ticks
    )
    x_tick_marks = "".join(
        f"<line x1='{x:.1f}' y1='{top + plot_h:.1f}' x2='{x:.1f}' y2='{top + plot_h + 6:.1f}' class='axis-line'></line>"
        for x, _ in x_ticks
    )
    x_tick_labels = "".join(
        f"<text x='{x:.1f}' y='{height - 8:.1f}' text-anchor='middle' class='axis-label'>{label}</text>"
        for x, label in x_ticks
    )

    return (
        f"<svg viewBox='0 0 {width} {height}' preserveAspectRatio='none'>"
        f"{y_tick_lines}"
        f"<line x1='{left:.1f}' y1='{top:.1f}' x2='{left:.1f}' y2='{top + plot_h:.1f}' class='axis-line'></line>"
        f"<line x1='{left:.1f}' y1='{top + plot_h:.1f}' x2='{left + plot_w:.1f}' y2='{top + plot_h:.1f}' class='axis-line'></line>"
        f"{x_tick_marks}"
        f"{y_tick_labels}"
        f"{x_tick_labels}"
        f"<polyline stroke='{color}' points='{points}'></polyline>"
        f"<text x='{width / 2:.1f}' y='{height - 2:.1f}' text-anchor='middle' class='axis-title'>Frame</text>"
        f"<text x='28' y='{top + plot_h / 2:.1f}' text-anchor='middle' class='axis-title' transform='rotate(-90 28 {top + plot_h / 2:.1f})'>{html.escape(unit)}</text>"
        "</svg>"
    )
