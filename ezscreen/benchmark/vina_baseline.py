def _code_cell(source: str, cell_id: str) -> dict[str, object]:
    return {
        "cell_type": "code",
        "id": cell_id,
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": [line + "\n" for line in source.splitlines()],
    }


def _prep_config(prep_cfg: dict[str, Any] | None) -> dict[str, Any]:
    cfg = dict(prep_cfg or {})
    cfg.setdefault("enable_gpu_size_filter", True)
    cfg.setdefault("max_heavy_atoms", 70)
    cfg.setdefault("max_mw", 700.0)
    cfg.setdefault("max_rotatable_bonds", 20)
    cfg.setdefault("mmff_max_iters", 0)
    cfg.setdefault("force_field", "MMFF94")
    cfg.setdefault("enumerate_enabled", True)
    cfg.setdefault("enumerate_protonation", True)
    cfg.setdefault("enumerate_tautomers", True)
    cfg.setdefault("enumerate_stereo", False)
    cfg.setdefault("enumerate_ring", False)
    cfg.setdefault("max_variants_per_ligand", 4)
    return cfg


